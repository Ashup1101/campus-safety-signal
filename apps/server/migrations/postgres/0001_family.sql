-- Family schema, mirroring the SQLite store (demo_server/store.py SCHEMA).
-- Timestamps stay ISO text and flags stay 0/1 integers so both backends behave the same.
-- Text uses the "C" collation so ordering matches SQLite's byte order.
create table accounts (
    id text collate "C" primary key,
    role text collate "C" not null check (role in ('student', 'parent', 'console')),
    display_name text collate "C" not null,
    is_test integer not null check (is_test in (0, 1)),
    email text collate "C",
    self_service integer not null default 0
);
create unique index accounts_email on accounts (email) where email is not null;
create table links (
    parent_id text collate "C" not null references accounts (id),
    student_id text collate "C" not null references accounts (id),
    parent_label text collate "C" not null,
    primary key (parent_id, student_id)
);
create table zones (
    id integer generated by default as identity primary key,
    account_id text collate "C" not null references accounts (id),
    name text collate "C" not null,
    lat double precision not null,
    lon double precision not null,
    radius_m integer not null
);
create table alerts (
    id text collate "C" primary key,
    source text collate "C" not null,
    kind text collate "C" not null,
    status text collate "C" not null,
    verification text collate "C" not null,
    test_only integer not null,
    official_at text collate "C",
    received_at text collate "C" not null,
    stored_text text collate "C" not null,
    link text collate "C",
    thread_id text collate "C"
);
create table deliveries (
    alert_id text collate "C" not null references alerts (id),
    account_id text collate "C" not null references accounts (id),
    client text collate "C" not null check (client in ('web', 'ios')),
    shown_at text collate "C" not null,
    primary key (alert_id, account_id, client)
);
create table mailbox (
    id integer generated by default as identity primary key,
    account_id text collate "C" not null references accounts (id),
    kind text collate "C" not null check (
        kind in ('briefing', 'digest', 'alert', 'correction', 'all_clear', 'account')
    ),
    subject text collate "C" not null,
    body text collate "C" not null,
    thread_id text collate "C",
    created_at text collate "C" not null
);
create table magic_tokens (
    hash text collate "C" primary key,
    account_id text collate "C" not null references accounts (id),
    issued_at text collate "C" not null,
    expires_at text collate "C" not null,
    used_at text collate "C"
);
create table invites (
    id integer generated by default as identity primary key,
    parent_id text collate "C" not null references accounts (id),
    student_email text collate "C" not null,
    status text collate "C" not null check (status in ('pending', 'accepted', 'declined')),
    created_at text collate "C" not null,
    relationship text collate "C"
);
create table ask_usage (
    account_id text collate "C" not null references accounts (id),
    day text collate "C" not null,
    count integer not null,
    primary key (account_id, day)
);
create table notes (
    id integer generated by default as identity primary key,
    thread_id text collate "C" not null,
    account_id text collate "C" not null references accounts (id),
    tag text collate "C" not null,
    text text collate "C",
    state text collate "C" not null check (state in ('held', 'pending', 'visible', 'hidden')),
    created_at text collate "C" not null,
    updated_at text collate "C" not null,
    unique (thread_id, account_id)
);
create table note_reports (
    note_id integer not null references notes (id) on delete cascade,
    account_id text collate "C" not null references accounts (id),
    primary key (note_id, account_id)
);
create table bans (
    account_id text collate "C" primary key references accounts (id),
    until text collate "C" not null
);
create table settings (
    key text collate "C" primary key,
    value text collate "C" not null
);
create table consents (
    account_id text collate "C" not null references accounts (id),
    kind text collate "C" not null,
    version text collate "C" not null,
    granted_at text collate "C",
    withdrawn_at text collate "C",
    primary key (account_id, kind)
);
create table subscriptions (
    account_id text collate "C" not null references accounts (id),
    kind text collate "C" not null,
    state text collate "C" not null check (state in ('pending_confirm', 'active', 'unsubscribed')),
    primary key (account_id, kind)
);
create table sub_tokens (
    hash text collate "C" primary key,
    account_id text collate "C" not null references accounts (id),
    kind text collate "C" not null,
    purpose text collate "C" not null check (purpose in ('confirm', 'unsubscribe')),
    created_at text collate "C" not null
);
create table survey_answers (
    account_id text collate "C" not null references accounts (id),
    prompt text collate "C" not null,
    q1 integer,
    q2 integer,
    q3 integer,
    answered_at text collate "C" not null,
    primary key (account_id, prompt)
);
create table device_keys (
    account_id text collate "C" primary key references accounts (id),
    key_id text collate "C" not null,
    secret text collate "C" not null,
    created_at text collate "C" not null,
    delivered integer not null default 0
);
create table sent_keys (
    key text collate "C" primary key,
    sent_at text collate "C" not null
);
create table activity (
    segment_id text collate "C" not null,
    time_window text collate "C" not null,
    level text collate "C" not null check (level in ('quiet', 'elevated', 'high')),
    reason text collate "C" not null,
    incidents integer not null,
    serious integer not null,
    primary key (segment_id, time_window)
);
